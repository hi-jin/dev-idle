#!/usr/bin/env node
// Builds code-dump/snippets.js and code-dump/NOTICE.md from the files listed in
// work/oss-sources/sources.json. Source files are only read, never executed.
//
//   node app/tools/build-code-dump.js [oss-sources-dir]
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const SRC = path.resolve(process.argv[2] || path.join(__dirname, '../../work/oss-sources'));
const OUT = path.resolve(__dirname, '../code-dump');
const ALLOWED = new Set(['MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause']);
const MIN_LINES = 30;
const MAX_LINES = 200;
const MIN_CODE_LINES = 15;
const MAX_BYTES = 1.5 * 1024 * 1024;

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function repoUrl(repository) {
  const raw = typeof repository === 'string' ? repository : repository && repository.url;
  if (!raw) return '';
  return raw.replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://');
}

function normalize(text) {
  return text
    .replace(/\r\n?/g, '\n')
    .replace(/\t/g, '  ')
    .split('\n')
    .map((line) => line.replace(/\s+$/, ''));
}

function isCodeLine(line) {
  const t = line.trim();
  return t !== '' && !t.startsWith('//') && !t.startsWith('*') && !t.startsWith('/*');
}

// Cut at blank lines once a chunk is long enough, and force a cut at MAX_LINES.
function chunk(lines) {
  const chunks = [];
  let start = 0;
  while (start < lines.length && lines[start] === '') start++;
  let cur = [];
  let curStart = start;
  for (let i = start; i < lines.length; i++) {
    cur.push(lines[i]);
    const atBlank = lines[i] === '' && cur.length >= MIN_LINES;
    if (atBlank || cur.length >= MAX_LINES) {
      chunks.push({ start: curStart + 1, lines: cur });
      cur = [];
      curStart = i + 1;
    }
  }
  if (cur.length >= MIN_LINES) chunks.push({ start: curStart + 1, lines: cur });
  return chunks;
}

function main() {
  const manifest = readJson(path.join(SRC, 'sources.json'));
  const sources = [];
  const snippets = [];
  const skipped = [];

  for (const entry of manifest.packages) {
    const dir = path.join(SRC, entry.pkg);
    const pkg = readJson(path.join(dir, 'package.json'));
    const license = typeof pkg.license === 'string' ? pkg.license : pkg.license && pkg.license.type;
    if (!ALLOWED.has(license)) {
      skipped.push(`${entry.pkg}: license ${license} is not allowed`);
      continue;
    }
    const licenseText = fs.readFileSync(path.join(dir, entry.licenseFile), 'utf8').trim();
    const copyright = (licenseText.split('\n').find((l) => /copyright/i.test(l)) || '').trim();
    const src = sources.length;
    sources.push({
      pkg: entry.pkg,
      version: pkg.version,
      repo: repoUrl(pkg.repository),
      license,
      copyright,
      licenseText,
      files: entry.files.map((f) => f.path),
    });

    for (const file of entry.files) {
      const lines = normalize(fs.readFileSync(path.join(dir, file.path), 'utf8'));
      for (const c of chunk(lines)) {
        while (c.lines.length && c.lines[c.lines.length - 1] === '') c.lines.pop();
        const text = c.lines.join('\n') + '\n';
        if (/[^\x20-\x7e\n]/.test(text)) {
          skipped.push(`${entry.pkg}/${file.path}:${c.start} has non-ASCII characters`);
          continue;
        }
        if (c.lines.filter(isCodeLine).length < MIN_CODE_LINES) {
          skipped.push(`${entry.pkg}/${file.path}:${c.start} is mostly comments`);
          continue;
        }
        snippets.push({
          id: `${entry.pkg}/${file.path}:${c.start}`,
          tag: file.tag,
          src,
          file: file.path,
          start: c.start,
          text,
        });
      }
    }
  }

  const dump = { generated: new Date().toISOString().slice(0, 10), sources, snippets };
  const js =
    '// Generated by tools/build-code-dump.js. Do not edit by hand.\n' +
    'window.Game = window.Game || {};\n' +
    'window.Game.codeDump = ' + JSON.stringify(dump) + ';\n';
  if (Buffer.byteLength(js) > MAX_BYTES) throw new Error(`snippets.js is ${Buffer.byteLength(js)} bytes, over the limit`);

  const notice = [
    '# Open-source notice',
    '',
    'The code you type in the game comes from these open-source packages. Each one is used under its own license, reproduced below.',
    '',
    ...sources.flatMap((s) => [
      `## ${s.pkg} ${s.version}`,
      '',
      `- License: ${s.license}`,
      `- Repository: ${s.repo}`,
      `- Files: ${s.files.join(', ')}`,
      '',
      '```',
      s.licenseText,
      '```',
      '',
    ]),
  ].join('\n');

  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, 'snippets.js'), js);
  fs.writeFileSync(path.join(OUT, 'NOTICE.md'), notice);

  const byTag = {};
  for (const s of snippets) byTag[s.tag] = (byTag[s.tag] || 0) + 1;
  console.log(`${snippets.length} snippets from ${sources.length} packages`, byTag);
  console.log(`snippets.js: ${(Buffer.byteLength(js) / 1024).toFixed(1)} KB`);
  if (skipped.length) console.log(`skipped ${skipped.length}:\n  ` + skipped.join('\n  '));
}

main();
